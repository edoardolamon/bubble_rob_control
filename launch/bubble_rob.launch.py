from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument, RegisterEventHandler
from launch.event_handlers import OnProcessExit
from launch.substitutions import (Command, FindExecutable, LaunchConfiguration,
                                  PathJoinSubstitution)
from launch_ros.actions import Node
from launch_ros.parameter_descriptions import ParameterValue
from launch_ros.substitutions import FindPackageShare


def generate_launch_description():
    # launch arguments first, so their values can be used below
    hardware_arg = DeclareLaunchArgument(
        "hardware", default_value="coppeliasim", description="coppeliasim or mock")

    pkg = FindPackageShare("bubble_rob_control")

    # the URDF, generated by xacro: used by robot_state_publisher
    robot_description = {"robot_description": ParameterValue(
        Command([FindExecutable(name="xacro"), " ",
                 PathJoinSubstitution([pkg, "urdf", "bubble_rob.urdf.xacro"]),
                 " hardware:=", LaunchConfiguration("hardware")]),
        value_type=str)}

    # controller_manager's parameters (update_rate, controllers): used by control_node
    controllers = PathJoinSubstitution([pkg, "config", "controllers.yaml"])

    robot_state_publisher = Node(
        package="robot_state_publisher", executable="robot_state_publisher",
        parameters=[robot_description], output="screen")

    control_node = Node(
        package="controller_manager", executable="ros2_control_node",
        parameters=[controllers], output="screen",
        remappings=[("~/robot_description", "/robot_description")])

    jsb_spawner = Node(
        package="controller_manager", executable="spawner",
        arguments=["joint_state_broadcaster", "--controller-manager", "/controller_manager"])

    diff_spawner = Node(
        package="controller_manager", executable="spawner",
        arguments=["diff_drive_controller", "--controller-manager", "/controller_manager"])

    range_spawner = Node(
        package="controller_manager", executable="spawner",
        arguments=["range_sensor_broadcaster", "--controller-manager", "/controller_manager"])

    # start the drive controller only after the broadcaster is active
    diff_after_jsb = RegisterEventHandler(
        OnProcessExit(target_action=jsb_spawner, on_exit=[diff_spawner]))

    return LaunchDescription(
        [hardware_arg, robot_state_publisher, control_node, jsb_spawner, range_spawner,
         diff_after_jsb])